#!/usr/bin/env bash
set -euo pipefail

ROOT="."
FORCE=false
DRY_RUN=false
COMMAND=""

usage() {
    echo "Usage: $0 <initialize|refresh> [--root <repository>] [--force] [--dry-run]"
    exit 1
}

while [[ $# -gt 0 ]]; do
    case "$1" in
        initialize|refresh) [[ -z "$COMMAND" ]] || usage; COMMAND="$1"; shift ;;
        --root) ROOT="$2"; shift 2 ;;
        --force) FORCE=true; shift ;;
        --dry-run) DRY_RUN=true; shift ;;
        -h|--help) usage ;;
        *) usage ;;
    esac
done

[[ -n "$COMMAND" && -d "$ROOT" ]] || usage
ROOT="$(cd "$ROOT" && pwd)"
OUTPUT="$ROOT/docs/project-map.md"

if [[ -e "$OUTPUT" && "$COMMAND" == "initialize" && "$FORCE" == false ]]; then
    echo "project map already exists: $OUTPUT (use refresh or --force)" >&2
    exit 1
fi

detect_stack() {
    local found=()
    [[ -f "$ROOT/pom.xml" || -f "$ROOT/mvnw" ]] && found+=("Java/Maven")
    [[ -f "$ROOT/build.gradle" || -f "$ROOT/build.gradle.kts" || -f "$ROOT/gradlew" ]] && found+=("Gradle")
    [[ -f "$ROOT/package.json" ]] && found+=("Node.js")
    [[ -f "$ROOT/composer.json" ]] && found+=("PHP/Composer")
    [[ -f "$ROOT/Cargo.toml" ]] && found+=("Rust/Cargo")
    [[ -f "$ROOT/go.mod" ]] && found+=("Go")
    [[ -f "$ROOT/pyproject.toml" || -f "$ROOT/requirements.txt" ]] && found+=("Python")
    (IFS=', '; echo "${found[*]:-No detectado}")
}

root_items() {
    find "$ROOT" -mindepth 1 -maxdepth 1 ! -name .git ! -name .codex ! -name .backup ! -name .DS_Store ! -name .env ! -name '.env.*' ! -name node_modules ! -name vendor ! -name .gradle ! -name build ! -name dist ! -name target -exec basename {} \; 2>/dev/null | sort
}

module_items() {
    for directory in app src packages modules services composeApp; do
        [[ -d "$ROOT/$directory" ]] || continue
        find "$ROOT/$directory" -mindepth 1 -maxdepth 1 -type d -exec sh -c 'for path; do printf "%s\\n" "$path"; done' sh {} + 2>/dev/null | sed "s#^$ROOT/##" | sort
    done
}

if $DRY_RUN; then
    echo "[dry-run] Would write $OUTPUT from repository structure and manifest names only."
    exit 0
fi

mkdir -p "$ROOT/docs"
TEMPORARY="$(mktemp "$ROOT/docs/.project-map.XXXXXX")"
trap 'rm -f "$TEMPORARY"' EXIT

{
    echo "# Project map"
    echo
    echo "Generated by \`scripts/project-memory.sh $COMMAND\`. Refresh after a structural change; keep architectural decisions in \`docs/decisions/\` and module-specific facts in \`docs/context/\`."
    echo
    echo "## Snapshot"
    echo
    echo "- Stack signals: $(detect_stack)"
    [[ -f "$ROOT/AGENTS.md" ]] && echo '- Root instruction file: `AGENTS.md`' || echo '- Root instruction file: not found'
    echo "- Generated map reads paths and manifest names only; it does not inspect environment files, secrets, logs, or dependencies."
    echo
    echo "## Top-level structure"
    echo
    root_items | sed 's/^/- `/' | sed 's/$/`/'
    echo
    echo "## Candidate modules"
    echo
    if module_items | grep -q .; then
        module_items | sed 's/^/- `/' | sed 's/$/`/'
    else
        echo "- No conventional module directories detected."
    fi
    echo
    echo "## Next reading"
    echo
    echo "1. Read \`AGENTS.md\` and \`docs/project-memory.md\`."
    echo "2. Read the relevant module context under \`docs/context/\`, when present."
    echo "3. Inspect the affected code and current evidence before selecting skills."
} > "$TEMPORARY"

mv "$TEMPORARY" "$OUTPUT"
trap - EXIT
echo "wrote: $OUTPUT"
